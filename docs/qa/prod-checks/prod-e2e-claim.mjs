// Production: signed-in QA user finds a real company, claims it and opens the radar.
import { chromium } from '/opt/node-tools/node_modules/playwright/index.mjs';
const base = 'https://bidfolio.co.uk';
const b = await chromium.launch({ proxy: { server: process.env.HTTPS_PROXY } });
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, storageState: '/home/user/.secrets/qa-state.json' });
const page = await ctx.newPage();
const errs = [];
page.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 140)); });
const shot = (n) => page.screenshot({ path: `/home/user/qa/prod/claim-${n}.png`, fullPage: true });
const text = async (sel = 'main') => (await page.locator(sel).first().innerText().catch(() => '')).replace(/\s+/g, ' ');
await page.goto(base + '/app/radar/find?q=roofing', { waitUntil: 'networkidle' });
console.log('find url:', page.url());
console.log('find text:', (await text()).slice(0, 500));
await shot('1-find');
const link = page.locator('a[href^="/claim/"]').first();
console.log('claim links:', await page.locator('a[href^="/claim/"]').count());
await link.click();
await page.waitForLoadState('networkidle');
console.log('claim url:', page.url());
console.log('claim text:', (await text()).slice(0, 500));
await shot('2-claim');
await page.getByTestId('claim-confirm').click();
await page.waitForLoadState('networkidle');
await page.waitForTimeout(3000);
console.log('radar url:', page.url());
console.log('radar text:', (await text()).slice(0, 1400));
await shot('3-radar');
console.log('console errors:', errs.slice(0, 5));
await ctx.storageState({ path: '/home/user/.secrets/qa-state.json' });
await b.close();
